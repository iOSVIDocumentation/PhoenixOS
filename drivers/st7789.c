static inline void lcd_cs_select(void) { gpio_put(PIN_LCD_CS, 0); }
static inline void lcd_cs_deselect(void) { gpio_put(PIN_LCD_CS, 1); }

static void lcd_write_cmd(uint8_t cmd) {
    gpio_put(PIN_LCD_DC, 0);
    lcd_cs_select();
    spi_write_blocking(LCD_SPI_PORT, &cmd, 1);
    lcd_cs_deselect();
}

static void lcd_write_data(uint8_t data) {
    gpio_put(PIN_LCD_DC, 1);
    lcd_cs_select();
    spi_write_blocking(LCD_SPI_PORT, &data, 1);
    lcd_cs_deselect();
}

static void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
    lcd_write_cmd(0x2A);
    lcd_write_data(x0 >> 8); lcd_write_data(x0 & 0xFF);
    lcd_write_data(x1 >> 8); lcd_write_data(x1 & 0xFF);
    lcd_write_cmd(0x2B);
    lcd_write_data(y0 >> 8); lcd_write_data(y0 & 0xFF);
    lcd_write_data(y1 >> 8); lcd_write_data(y1 & 0xFF);
    lcd_write_cmd(0x2C);
}

void st7789_set_backlight(uint8_t percent) {
    if (percent > 100) percent = 100;
    uint16_t duty = (percent * 10000) / 100;
    pwm_set_gpio_level(PIN_LCD_BLK, duty);
}

void st7789_init(void) {
    gpio_init(PIN_LCD_CS);
    gpio_set_dir(PIN_LCD_CS, GPIO_OUT);
    gpio_put(PIN_LCD_CS, 1);

    gpio_init(PIN_LCD_DC);
    gpio_set_dir(PIN_LCD_DC, GPIO_OUT);
    gpio_put(PIN_LCD_DC, 0);

    gpio_init(PIN_LCD_RST);
    gpio_set_dir(PIN_LCD_RST, GPIO_OUT);
    gpio_put(PIN_LCD_RST, 1);

    spi_init(LCD_SPI_PORT, 10 * 1000 * 1000);
    spi_set_format(LCD_SPI_PORT, 8, SPI_CPOL_0, SPI_CPHA_0, SPI_MSB_FIRST);
    gpio_set_function(PIN_LCD_SCK, GPIO_FUNC_SPI);
    gpio_set_function(PIN_LCD_MOSI, GPIO_FUNC_SPI);

    gpio_set_function(PIN_LCD_BLK, GPIO_FUNC_PWM);
    pwm_slice_num = pwm_gpio_to_slice_num(PIN_LCD_BLK);
    pwm_config cfg = pwm_get_default_config();
    pwm_config_set_wrap(&cfg, 10000);
    pwm_config_set_clkdiv(&cfg, 1.0f);
    pwm_init(pwm_slice_num, &cfg, true);
    st7789_set_backlight(0);

    gpio_put(PIN_LCD_RST, 0);
    sleep_ms(20);
    gpio_put(PIN_LCD_RST, 1);
    sleep_ms(120);

    lcd_write_cmd(0x01); sleep_ms(150);
    lcd_write_cmd(0x11); sleep_ms(120);
    lcd_write_cmd(0x3A); lcd_write_data(0x05);
    lcd_write_cmd(0x36); lcd_write_data(0xA0);
    lcd_write_cmd(0x20); sleep_ms(10);
    lcd_write_cmd(0x13); sleep_ms(10);

    lcd_write_cmd(0x29); sleep_ms(50);
    st7789_fill(0x0000);

    st7789_set_backlight(100);
}

void st7789_fill(uint16_t color) { st7789_fill_rect(0, 0, LCD_WIDTH, LCD_HEIGHT, color); }

void st7789_fill_rect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
    if ((x >= LCD_WIDTH) || (y >= LCD_HEIGHT)) return;
    if ((x + w - 1) >= LCD_WIDTH) w = LCD_WIDTH - x;
    if ((y + h - 1) >= LCD_HEIGHT) h = LCD_HEIGHT - y;
    if (w <= 0 || h <= 0) return;

    static uint8_t fill_buf[LCD_WIDTH * 2];
    for (int16_t i = 0; i < w; i++) {
        fill_buf[2 * i] = color >> 8;
        fill_buf[2 * i + 1] = color & 0xFF;
    }
    for (int16_t row = y; row < y + h; row++) {
        lcd_set_window(x, row, x + w - 1, row);
        gpio_put(PIN_LCD_DC, 1);
        lcd_cs_select();
        spi_write_blocking(LCD_SPI_PORT, fill_buf, (size_t)w * 2);
        lcd_cs_deselect();
    }
}

void st7789_draw_pixel(int16_t x, int16_t y, uint16_t color) {
    if (x < 0 || x >= LCD_WIDTH || y < 0 || y >= LCD_HEIGHT) return;
    st7789_fill_rect(x, y, 1, 1, color);
}

void st7789_draw_rect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
    st7789_fill_rect(x, y, w, 1, color);
    st7789_fill_rect(x, y + h - 1, w, 1, color);
    st7789_fill_rect(x, y, 1, h, color);
    st7789_fill_rect(x + w - 1, y, 1, h, color);
}

void st7789_draw_char(int16_t x, int16_t y, char ch, uint16_t color, uint16_t bg, uint8_t scale) {
    if (ch < 32 || ch > 126) ch = '?';
    uint8_t c_idx = ch - 32;
    for (uint8_t i = 0; i < 8; i++) {
        uint8_t line = font8x8_basic[c_idx][i];
        for (uint8_t j = 0; j < 8; j++) {
            if (line & (0x80 >> j)) {
                if (scale == 1) st7789_draw_pixel(x + j, y + i, color);
                else st7789_fill_rect(x + j * scale, y + i * scale, scale, scale, color);
            } else if (bg != color) {
                if (scale == 1) st7789_draw_pixel(x + j, y + i, bg);
                else st7789_fill_rect(x + j * scale, y + i * scale, scale, scale, bg);
            }
        }
    }
}

void st7789_draw_string(int16_t x, int16_t y, const char *str, uint16_t color, uint16_t bg, uint8_t scale) {
    int16_t curr_x = x;
    while (*str) {
        st7789_draw_char(curr_x, y, *str, color, bg, scale);
        curr_x += 8 * scale;
        str++;
    }
}

static uint8_t fast_buf[LCD_WIDTH * 2];

void st7789_draw_string_fast(int16_t x, int16_t y, const char *str, uint16_t color, uint16_t bg, uint8_t max_chars) {
    if (x < 0 || y < 0 || y + 8 > LCD_HEIGHT) return;
    int16_t width_px = (int16_t)max_chars * 8;
    if (x + width_px > LCD_WIDTH) width_px = LCD_WIDTH - x;
    if (width_px <= 0) return;

    uint8_t hi_c = color >> 8, lo_c = color & 0xFF;
    uint8_t hi_b = bg >> 8, lo_b = bg & 0xFF;

    for (uint8_t row = 0; row < 8; row++) {
        for (int16_t i = 0; i < width_px; i++) {
            fast_buf[2 * i] = hi_b;
            fast_buf[2 * i + 1] = lo_b;
        }
        int16_t px = 0;
        const char *p = str;
        uint8_t n = 0;
        while (*p && n < max_chars) {
            char ch = *p;
            if (ch < 32 || ch > 126) ch = '?';
            uint8_t bits = font8x8_basic[(uint8_t)(ch - 32)][row];
            for (uint8_t j = 0; j < 8; j++) {
                int16_t idx = px + j;
                if (idx >= width_px) break;
                if (bits & (0x80 >> j)) {
                    fast_buf[2 * idx] = hi_c;
                    fast_buf[2 * idx + 1] = lo_c;
                }
            }
            px += 8;
            n++;
            p++;
        }
        lcd_set_window(x, y + row, x + width_px - 1, y + row);
        gpio_put(PIN_LCD_DC, 1);
        lcd_cs_select();
        spi_write_blocking(LCD_SPI_PORT, fast_buf, (size_t)width_px * 2);
        lcd_cs_deselect();
    }
}

void st7789_write_row(int16_t x, int16_t y, int16_t w, const uint8_t *buf) {
    if (x < 0 || y < 0 || w <= 0 || y >= LCD_HEIGHT) return;
    if (x + w > LCD_WIDTH) w = LCD_WIDTH - x;
    lcd_set_window(x, y, x + w - 1, y);
    gpio_put(PIN_LCD_DC, 1);
    lcd_cs_select();
    spi_write_blocking(LCD_SPI_PORT, buf, (size_t)w * 2);
    lcd_cs_deselect();
}

uint8_t st7789_font_row(char ch, uint8_t row) {
    if (ch < 32 || ch > 126) ch = '?';
    if (row > 7) return 0;
    return font8x8_basic[(uint8_t)(ch - 32)][row];
}

void st7789_display_on(void) {
    lcd_write_cmd(0x11);
    sleep_ms(10);
    lcd_write_cmd(0x29);
    sleep_ms(10);
}
